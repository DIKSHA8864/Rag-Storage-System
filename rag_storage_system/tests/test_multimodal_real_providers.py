class _FakeWhisperModel:
    def __init__(self, transcript_text: str):
        self._transcript_text = transcript_text
        self.last_path: str | None = None

    def transcribe(self, path: str):
        self.last_path = path
        segment = SimpleNamespace(text=self._transcript_text)
        return [segment], SimpleNamespace(language="en")


def test_whisper_transcribes_audio_bytes_via_a_temp_file(monkeypatch):
    fake_model = _FakeWhisperModel(" Hello from the client. ")
    provider = WhisperSTTProvider()
    monkeypatch.setattr(provider, "_load_model", lambda: fake_model)

    transcript, is_mock = provider.transcribe(b"fake audio bytes", "call.mp3")

    assert transcript == "Hello from the client."
    assert is_mock is False
    assert fake_model.last_path.endswith(".mp3")
    assert not Path(fake_model.last_path).exists()  # cleaned up after transcription


def test_whisper_joins_multiple_segments():
    class _MultiSegmentModel:
        def transcribe(self, path):
            return (
                [SimpleNamespace(text="First sentence."), SimpleNamespace(text="Second sentence.")],
                SimpleNamespace(language="en"),
            )

    provider = WhisperSTTProvider()
    provider._load_model = lambda: _MultiSegmentModel()

    transcript, _ = provider.transcribe(b"fake audio bytes", "note.wav")

    assert transcript == "First sentence. Second sentence."


def test_whisper_wraps_transcription_failures():
    class _BrokenModel:
        def transcribe(self, path):
            raise ValueError("boom")

    provider = WhisperSTTProvider()
    provider._load_model = lambda: _BrokenModel()

    with pytest.raises(RuntimeError, match="Whisper transcription failed"):
        provider.transcribe(b"fake audio bytes", "call.mp3")


@pytest.mark.skipif(shutil.which("ffmpeg") is None, reason="ffmpeg not installed in this environment")
def test_whisper_transcribes_a_video_file_with_no_separate_demuxing_step(tmp_path, monkeypatch):
    """
    The whole point of WhisperSTTProvider handling video: no video-
    specific code path exists anywhere (app/multimodal/video_processor.py
    calls the exact same transcribe() audio_processor.py does) -
    faster-whisper's own PyAV-based decoding demuxes the audio stream
    out of the video container. This proves that decoding step works
    against a REAL video file (synthesized here, no network/fixture
    file needed), by handing it a video path and confirming the (fake)
    model was invoked with that same, still-decodable file.
    """

    video_path = tmp_path / "clip.mp4"
    subprocess.run(
        [
            "ffmpeg", "-y", "-f", "lavfi", "-i", "sine=frequency=440:duration=1",
            "-f", "lavfi", "-i", "testsrc=duration=1:size=160x120:rate=5",
            "-c:v", "libx264", "-c:a", "aac", "-shortest", str(video_path),
        ],
        check=True, capture_output=True,
    )
    video_bytes = video_path.read_bytes()

    fake_model = _FakeWhisperModel("Deposition audio transcribed from the video's audio track.")
    provider = WhisperSTTProvider()
    monkeypatch.setattr(provider, "_load_model", lambda: fake_model)

    transcript, is_mock = provider.transcribe(video_bytes, "clip.mp4")

    assert transcript == "Deposition audio transcribed from the video's audio track."
    assert is_mock is False
    assert fake_model.last_path.endswith(".mp4")

    # Confirm PyAV (what faster-whisper actually uses to decode) can
    # open this exact video and find a real, decodable audio stream -
    # the real mechanism this test's fake model call stands in for.
    import av

    with av.open(str(video_path)) as container:
        audio_streams = [s for s in container.streams if s.type == "audio"]
        assert len(audio_streams) == 1
        assert sum(1 for _ in container.decode(audio_streams[0])) > 0


