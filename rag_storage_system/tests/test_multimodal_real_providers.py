@dataclass
class _FakeSettings:
    anthropic_api_key: str = "test-key"
    analysis_model: str = "claude-opus-5"
    vision_provider: str = "claude"


def _fake_anthropic_client(response_text: str):
    block = SimpleNamespace(type="text", text=response_text)
    usage = SimpleNamespace(input_tokens=15, output_tokens=25)
    response = SimpleNamespace(content=[block], usage=usage)

    class _FakeMessages:
        def create(self, **kwargs):
            _FakeMessages.last_call = kwargs
            return response

    return SimpleNamespace(messages=_FakeMessages())


def test_claude_vision_describes_an_image(monkeypatch):
    monkeypatch.setattr("app.multimodal.vision.get_settings", lambda: _FakeSettings())
    monkeypatch.setattr("anthropic.Anthropic", lambda api_key: _fake_anthropic_client("A photo of a damaged vehicle."))

    provider = ClaudeVisionProvider()
    caption, is_mock = provider.describe(_text_image_bytes("irrelevant"), "scene.png")

    assert caption == "A photo of a damaged vehicle."
    assert is_mock is False


def test_claude_vision_sends_the_image_as_a_base64_content_block(monkeypatch):
    monkeypatch.setattr("app.multimodal.vision.get_settings", lambda: _FakeSettings())
    fake_client = _fake_anthropic_client("caption")
    monkeypatch.setattr("anthropic.Anthropic", lambda api_key: fake_client)

    provider = ClaudeVisionProvider()
    provider.describe(_text_image_bytes("irrelevant"), "scene.png")

    sent_content = fake_client.messages.last_call["messages"][0]["content"]
    image_block = next(b for b in sent_content if b["type"] == "image")
    assert image_block["source"]["media_type"] == "image/png"
    assert isinstance(image_block["source"]["data"], str)


